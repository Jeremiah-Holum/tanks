// Pick n distinct names with a seeded rng, skipping any in `exclude`.
export function pickNames(rng, n, exclude = []) {
  const pool = NAMES.filter((x) => !exclude.includes(x));
  for (let i = pool.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [pool[i], pool[j]] = [pool[j], pool[i]]; }
  const out = pool.slice(0, n);
  while (out.length < n) out.push('Recruit_' + (100 + Math.floor(rng() * 900)));
  return out;
}
