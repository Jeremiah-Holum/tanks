js += "export const CAMPAIGN = " + json.dumps(out['campaign'], indent=1) + ";\n"
js += "export const VERSUS = " + json.dumps(out['versus'], indent=1) + ";\n"
open(sys.argv[1], 'w').write(js)
print('ok', len(CAMPAIGN), len(VERSUS))
