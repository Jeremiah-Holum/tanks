import json, sys
def check(name, s):
    rows = s.strip('\n').split('\n')
    errs = []
    if len(rows) != 16: errs.append(f"{name}: {len(rows)} rows")
    for k, r in enumerate(rows):
        if len(r) != 22: errs.append(f"{name}: row {k} is {len(r)} wide: {r!r}")
    return rows, errs
out, errs = {'campaign': [], 'versus': []}, []
for key, lst in (('campaign', CAMPAIGN), ('versus', VERSUS)):
    for name, s in lst:
        rows, e = check(name, s); errs += e
        out[key].append({'name': name, 'rows': rows})
if errs:
    print('\n'.join(errs)); sys.exit(1)
